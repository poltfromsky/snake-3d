/** Текст подсказки шага для устройства игрока. */
export function stepText(step, device) {
  return step.text[device] ?? step.text.all ?? '';
}

/** Чем управляет игрок: определяет текст подсказок. */
export function controlDevice({ touch, controls }) {
  if (!touch) return 'keys';
  return controls === 'buttons' ? 'buttons' : 'swipe';
}
