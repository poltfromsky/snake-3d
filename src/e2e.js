/**
 * Тестовый режим для браузерных автотестов (Playwright, папка e2e/).
 *
 * Включается только параметром `?e2e` в адресе. Тогда игра выкладывает в
 * `window.__snakeE2E` доступ к своему состоянию: тест может проверить, какой
 * экран открыт, и подготовить позицию (например, поставить бота перед стеной),
 * не дожидаясь, пока это случится само. Обычные игроки этот режим не видят.
 */
export const E2E = new URLSearchParams(globalThis.location?.search ?? '').has('e2e');

/** @param {object} api объект с геттерами состояния игры */
export function exposeForTests(api) {
  if (E2E) globalThis.__snakeE2E = api;
}
